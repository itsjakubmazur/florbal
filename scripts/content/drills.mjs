const p = (at, blade, extra = {}) => (blade ? { at, blade, ...extra } : { at, ...extra });
const a = (n, dir, blade, extra = {}) => ({ at: `around:${n}`, dir, ...(blade ? { blade } : {}), ...extra });
const top = (at, blade) => p(at, blade, { hand: 'top' });
const bot = (at, blade) => p(at, blade, { hand: 'bottom' });

